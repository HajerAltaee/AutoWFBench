"""Trusted evaluation adapters and the numeric-only projection boundary."""
from __future__ import annotations

from autowfbench.composer.candidate_runtime import handler_for
from autowfbench.composer.models import NumericObservation, validate_candidate
from autowfbench.core.common import background_server


class LocalBenchmarkEvaluator:
    """Evaluate candidates with the unchanged Engine, then discard all details."""

    def __init__(self, engine, challenge_id):
        self.engine, self.challenge_id = engine, challenge_id

    def evaluate(self, candidate, seed, repeat):
        validate_candidate(candidate, expected_challenge=self.challenge_id)
        server = background_server(handler_for(candidate))
        try:
            manifest = {
                "id": candidate["candidate_id"].replace("_", "-"),
                "name": "Composer " + candidate["candidate_id"],
                "version": candidate["version"],
                "endpoint": f"http://127.0.0.1:{server.server_port}",
                "runtime": "composer-declarative-v1",
                "description": "Generated by the black-box Composer",
                "auth_env": "",
            }
            run_id = self.engine.submit(self.challenge_id, manifest, seed=seed, background=False)
            # This is the sole projection point. Detailed fields are not returned.
            return NumericObservation.from_engine_result(candidate["candidate_id"], self.engine.read(run_id))
        finally:
            server.shutdown()
            server.server_close()
